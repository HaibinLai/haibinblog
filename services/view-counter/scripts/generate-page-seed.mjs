import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SERVICE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_POSTS_ROOT = path.resolve(SERVICE_ROOT, "../../src/content/posts");
const DEFAULT_OUTPUT = path.resolve(SERVICE_ROOT, "page-seed.sql");

async function markdownFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) return markdownFiles(absolute);
      return entry.isFile() && entry.name.endsWith(".md") ? [absolute] : [];
    }),
  );
  return files.flat();
}

function frontmatterOf(source, filename) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/u);
  if (!match) throw new Error(`${filename}: missing YAML frontmatter`);
  return match[1];
}

function scalar(frontmatter, key) {
  const match = frontmatter.match(new RegExp(`^${key}:\\s*(.*?)\\s*$`, "mu"));
  if (!match) return undefined;
  const raw = match[1];
  if (raw.startsWith('"')) return JSON.parse(raw);
  if (raw.startsWith("'") && raw.endsWith("'")) {
    return raw.slice(1, -1).replaceAll("''", "'");
  }
  return raw;
}

function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function postPath(slug) {
  const normalized = slug.normalize("NFC").replace(/^\/+|\/+$/gu, "");
  if (!normalized || normalized.includes("..") || normalized.includes("\\")) {
    throw new Error(`unsafe post slug: ${slug}`);
  }
  return `/posts/${normalized}/`;
}

export async function generatePageSeed({
  postsRoot = DEFAULT_POSTS_ROOT,
  output = DEFAULT_OUTPUT,
} = {}) {
  const rows = [];
  for (const filename of await markdownFiles(postsRoot)) {
    const source = await readFile(filename, "utf8");
    const frontmatter = frontmatterOf(source, filename);
    if (String(scalar(frontmatter, "draft") || "false").toLowerCase() === "true") continue;

    const viewCountRaw = scalar(frontmatter, "viewCount");
    if (viewCountRaw === undefined) continue;
    const viewCount = Number(viewCountRaw);
    if (!Number.isSafeInteger(viewCount) || viewCount < 0) {
      throw new Error(`${filename}: viewCount must be a non-negative integer`);
    }

    const relative = path.relative(postsRoot, filename).replace(/\\/gu, "/").replace(/\.md$/u, "");
    const slug = scalar(frontmatter, "slug") || relative.replace(/^wordpress\//u, "");
    rows.push({ path: postPath(String(slug)), viewCount, filename });
  }

  rows.sort((left, right) => left.path.localeCompare(right.path, "en"));
  const seen = new Map();
  for (const row of rows) {
    if (seen.has(row.path)) {
      throw new Error(`duplicate route ${row.path}: ${seen.get(row.path)} and ${row.filename}`);
    }
    seen.set(row.path, row.filename);
  }

  const historicalPageSum = rows.reduce((sum, row) => sum + row.viewCount, 0);
  const values = rows.map(
    (row) => `  (${sqlString(row.path)}, ${row.viewCount}, unixepoch())`,
  );
  const sql = [
    "-- Generated by scripts/generate-page-seed.mjs from post frontmatter.",
    "-- Do not add the per-page sum to the independent 363842 site baseline.",
    `-- Seeded pages: ${rows.length}; historical per-page sum: ${historicalPageSum}.`,
    "INSERT INTO view_counts (path, total, updated_at)",
    "VALUES",
    values.join(",\n"),
    "ON CONFLICT(path) DO NOTHING;",
    "",
  ].join("\n");
  await writeFile(output, sql, "utf8");
  return { count: rows.length, historicalPageSum, output };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await generatePageSeed();
  console.log(
    `generated ${result.count} page baselines (sum ${result.historicalPageSum}) at ${result.output}`,
  );
}
